seq=[2200,2300,1200,2300,2300,1100,2300,1100,1100,2300,1700,2200,2200,1700,1200,2200,1700,2300,2200,2300,1100,2300,1200,2300,2200,1700,2300,2300,2300,1200,2200,1100,1100,1100,1100,1100,2300,2200,1600,2300,1100,2300,2200,1100,1200,1100,1700,1100,2300,2300,1200,2300,2300,2300,2300,2300,2300,2200,1700,2300,1200,1800,1700,1200,1100,2200,2300,2300,2300,2300,1100,2300,2200,1100,1100,1100,2200,1600,1100,1100,1100]
syms=[1100,1200,1600,1700,1800,2200,2300,600]
for perm in itertools.permutations(range(8)):
 mp={syms[i]:format(perm[i],'03b') for i in range(8)}
 bits=''.join(mp.get(x,'000') for x in seq)
 for off in range(8):
  data=''.join(chr(int(bits[i:i+8],2)) for i in range(off,len(bits)-7,8))
  if sum(c.isalnum() or c in '{}_' for c in data)>len(data)*0.8: print(mp,off,repr(data))
print('done')
