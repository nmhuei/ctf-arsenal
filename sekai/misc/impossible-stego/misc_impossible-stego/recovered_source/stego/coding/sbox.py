"""
sbox.py — keyed bijective 8-bit substitution box.

A 256-entry permutation of the byte space, generated by a CSPRNG seeded from
the schedule's S-box key mixed with the baked-in SBOX_SEED.  Applied to the
ciphertext as a confusion layer: every byte is mapped through the S-box on
embed and through its inverse on extract.  Because the permutation is keyed and
image-bound, the mapping is unique per image geometry.
"""

import hashlib

from ..crypto.csprng import Csprng
from .. import secret


class Sbox:
    def __init__(self, sbox_key: bytes):
        seed = hashlib.sha256(sbox_key + secret.SBOX_SEED).digest()
        self._forward = Csprng(seed).permutation(256)
        self._inverse = [0] * 256
        for i, v in enumerate(self._forward):
            self._inverse[v] = i

    def apply(self, data: bytes) -> bytes:
        fwd = self._forward
        return bytes(fwd[b] for b in data)

    def invert(self, data: bytes) -> bytes:
        inv = self._inverse
        return bytes(inv[b] for b in data)
