  x=b[pc]
  if 0x60<=x<=0x7f:
   n=x-0x5f; print(f'{pc:08x}: PUSH{n} 0x{b[pc+1:pc+1+n].hex()}'); pc+=1+n
  elif 0x80<=x<=0x8f: print(f'{pc:08x}: DUP{x-0x7f}'); pc+=1
  elif 0x90<=x<=0x9f: print(f'{pc:08x}: SWAP{x-0x8f}'); pc+=1
  else: print(f'{pc:08x}: {names.get(x,hex(x))}'); pc+=1
